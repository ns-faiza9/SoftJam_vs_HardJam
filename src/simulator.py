"""
StartSense - Motor Startup Simulation Engine (High-Stability Numerical Physics)
Variant: 02.08 – Soft-Jam versus Hard-Jam Starter

NOTE:
All motor-related telemetry (current, speed, encoder pulse timing, temperature)
generated by this engine is SYNTHETIC / SIMULATED.
The potentiometer reading from STM32 represents REAL HARDWARE INPUT.
"""

import sys
from pathlib import Path

# Add project root to path for PyCharm standalone execution
PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

import numpy as np
import pandas as pd
from typing import Dict, Any, Tuple
from src.config import (
    CLASS_NORMAL, CLASS_SOFT_JAM, CLASS_HARD_JAM,
    DEFAULT_MOTOR_SPECS, SAFETY_LIMITS
)

class MotorStartupSimulator:
    def __init__(self, specs: Dict[str, Any] = None):
        self.specs = specs or DEFAULT_MOTOR_SPECS.copy()

    def simulate_episode(
        self,
        condition: str = CLASS_NORMAL,
        load_severity: float = None,
        pwm_duty: float = 100.0,
        direction: str = "FORWARD",
        ambient_temp: float = 25.0,
        noise_level: float = 0.05,
        duration_sec: float = 3.0,
        sample_rate_hz: int = 100,
        seed: int = None
    ) -> Tuple[pd.DataFrame, Dict[str, Any]]:
        """
        Simulates an independent startup transient run using stable sub-stepped physics.
        """
        if seed is not None:
            np.random.seed(seed)

        dt_sample = 1.0 / sample_rate_hz
        time_steps = int(duration_sec * sample_rate_hz)
        time_array = np.linspace(0, duration_sec, time_steps)

        # Direction multiplier
        dir_mult = 1.0 if direction == "FORWARD" else -1.0
        v_bus = self.specs["V_BUS"] * (pwm_duty / 100.0)

        # Determine load severity proxy [0.0 - 1.0]
        if load_severity is None:
            if condition == CLASS_NORMAL:
                load_severity = float(np.random.uniform(0.05, 0.22))
            elif condition == CLASS_SOFT_JAM:
                load_severity = float(np.random.uniform(0.45, 0.68))
            else:  # HARD JAM
                load_severity = float(np.random.uniform(0.85, 1.00))
        else:
            load_severity = float(np.clip(load_severity, 0.0, 1.0))

        # Physical constants
        R = float(self.specs["R_STATOR"])
        L = float(self.specs["L_STATOR"])
        Kt = float(self.specs["K_TORQUE"])
        Ke = float(self.specs["K_EMF"])
        J = float(self.specs["ROTOR_INERTIA"])
        B = float(self.specs["VISCOUS_DAMPING"])
        cpr = int(self.specs["ENCODER_CPR"])
        rad_per_pulse = (2.0 * np.pi) / cpr

        # Load & friction based on severity
        # Normal: ~0.15 - 0.35 Nm, Soft Jam: ~0.8 - 1.4 Nm, Hard Jam: > 2.6 Nm
        static_friction = 0.08 + (0.25 * load_severity)
        coulomb_friction = 0.05 + (0.30 * load_severity)
        external_jam_torque = load_severity * 2.8

        # Numerical sub-stepping for differential equation stability
        # Sub-step at 0.4 ms (2500 Hz)
        n_substeps = 25
        dt_sub = dt_sample / n_substeps

        # State variables
        current = 0.0
        omega = 0.0  # rad/s
        rotor_theta = 0.0
        temp = float(ambient_temp)
        last_pulse_theta = 0.0
        last_pulse_time = 0.0
        current_pulse_interval_ms = 45.0

        current_records = []
        speed_records = []
        temp_records = []
        pulse_records = []
        pwm_records = []

        for sample_i, t_now in enumerate(time_array):
            for sub_i in range(n_substeps):
                t_sub = t_now + (sub_i * dt_sub)
                
                # Soft start PWM ramp in first 40 ms
                ramp = min(1.0, max(0.05, t_sub / 0.04))
                v_app = v_bus * ramp

                # Back EMF
                e_back = Ke * omega

                # Electrical Euler step
                di_dt = (v_app - (R * current) - e_back) / L
                current += di_dt * dt_sub
                # Clamp current to realistic physical saturation limits
                current = float(np.clip(current, 0.0, 26.0))

                # Torque calculation
                t_em = Kt * current

                # Mechanical resistance
                if abs(omega) < 0.05:
                    # Static holding condition
                    breakaway_torque = static_friction + external_jam_torque
                    if t_em < breakaway_torque:
                        omega = 0.0
                        domega_dt = 0.0
                    else:
                        domega_dt = (t_em - breakaway_torque) / J
                        omega += domega_dt * dt_sub
                else:
                    t_res = coulomb_friction + (B * omega) + external_jam_torque
                    t_net = t_em - t_res
                    domega_dt = t_net / J
                    omega += domega_dt * dt_sub
                    if omega < 0.0:
                        omega = 0.0

                # Max speed physical governor (no runaway)
                omega = float(np.clip(omega, 0.0, 380.0))  # ~3600 RPM max
                
                # Angle and pulse tracking
                d_theta = omega * dt_sub
                rotor_theta += d_theta

                if rotor_theta - last_pulse_theta >= rad_per_pulse:
                    time_since = max(0.0002, t_sub - last_pulse_time)
                    current_pulse_interval_ms = time_since * 1000.0
                    last_pulse_theta = rotor_theta
                    last_pulse_time = t_sub
                elif t_sub - last_pulse_time > 0.08:
                    # Stalled or ultra slow
                    current_pulse_interval_ms = min(150.0, (t_sub - last_pulse_time) * 1000.0)

                # Thermal integration (I^2 * R heating + natural convective cooling)
                joule_heating = (current ** 2) * R * 0.0035  # °C per second
                cooling = (temp - ambient_temp) * 0.03
                temp += (joule_heating - cooling) * dt_sub

            # Store sampled record with realistic sensor noise
            rpm = (omega * 60.0) / (2.0 * np.pi)

            # Realistic sensor noise
            i_noise = np.random.normal(0, max(0.04, current * noise_level * 0.25))
            rpm_noise = np.random.normal(0, max(4.0, rpm * noise_level * 0.15))
            temp_noise = np.random.normal(0, 0.05)
            pulse_noise = np.random.normal(0, max(0.1, current_pulse_interval_ms * noise_level * 0.2))

            curr_sample = max(0.0, current + i_noise)
            rpm_sample = max(0.0, rpm + rpm_noise)
            temp_sample = max(ambient_temp - 1.0, temp + temp_noise)
            pulse_sample = max(0.3, current_pulse_interval_ms + pulse_noise)

            current_records.append(round(curr_sample, 3))
            speed_records.append(round(rpm_sample, 1))
            temp_records.append(round(temp_sample, 2))
            pulse_records.append(round(pulse_sample, 2))
            pwm_records.append(float(pwm_duty))

        telemetry_df = pd.DataFrame({
            "time_sec": np.round(time_array, 4),
            "current_sim_amp": current_records,
            "speed_sim_rpm": speed_records,
            "temp_sim_celsius": temp_records,
            "encoder_interval_ms": pulse_records,
            "pwm_duty": pwm_records,
            "direction": [direction] * time_steps,
            "is_simulated": [True] * time_steps
        })

        meta = {
            "target_condition": condition,
            "load_severity_proxy": round(load_severity, 3),
            "pwm_duty": pwm_duty,
            "direction": direction,
            "ambient_temp": ambient_temp,
            "noise_level": noise_level,
            "duration_sec": duration_sec,
            "sample_count": time_steps,
            "signal_mode": "SYNTHETIC_SIMULATION",
            "physical_potentiometer_input": None
        }

        return telemetry_df, meta

